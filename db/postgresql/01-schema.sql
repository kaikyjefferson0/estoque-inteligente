-- Recorte de fornecedores e produtos para a aula. As migrations do Alembic
-- continuam sendo a fonte do esquema usado pela aplicação.
CREATE SCHEMA estoque_aula;

CREATE TABLE estoque_aula.suppliers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    nome VARCHAR(120) NOT NULL,
    cnpj VARCHAR(14),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT suppliers_pkey PRIMARY KEY (id),
    CONSTRAINT uq_suppliers_cnpj UNIQUE (cnpj),
    CONSTRAINT ck_suppliers_cnpj_14_digitos CHECK (cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE estoque_aula.products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    nome VARCHAR(120) NOT NULL,
    codigo_barras VARCHAR(50) NOT NULL,
    estoque_minimo INTEGER NOT NULL DEFAULT 0,
    controla_validade BOOLEAN NOT NULL DEFAULT FALSE,
    dias_alerta_validade INTEGER,
    fornecedor_id INTEGER,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT products_pkey PRIMARY KEY (id),
    CONSTRAINT fk_products_fornecedor_id_suppliers
        FOREIGN KEY (fornecedor_id) REFERENCES estoque_aula.suppliers (id) ON DELETE RESTRICT,
    CONSTRAINT ck_products_estoque_minimo_nao_negativo CHECK (estoque_minimo >= 0),
    CONSTRAINT ck_products_dias_alerta_validade CHECK (
        (controla_validade AND dias_alerta_validade IS NOT NULL AND dias_alerta_validade > 0)
        OR (NOT controla_validade AND dias_alerta_validade IS NULL)
    ),
    -- Mesmos espaços de str.split() usados pela migration 9a0c1c19b39f,
    -- escritos com escapes para deixar visíveis os limites dos intervalos.
    CONSTRAINT ck_products_codigo_barras_sem_espacos CHECK (
        codigo_barras !~ '[\u0009-\u000d\u001c-\u0020\u0085\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000]'
    )
);

CREATE UNIQUE INDEX ix_products_codigo_barras ON estoque_aula.products (codigo_barras);
CREATE INDEX ix_products_fornecedor_id ON estoque_aula.products (fornecedor_id);
